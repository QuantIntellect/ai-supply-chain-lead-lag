def data_dictionary():
    parts = ["# Data dictionary\n", "Schema, row count and one example row for each key dataset. Files marked _local only_ are not in git "
             "(see the data policy in README.md) and are rebuilt by the pipeline.\n"]
    for rel, desc in DATASETS:
        p = os.path.join(ROOT, rel)
        parts.append(f"\n## `{rel}`\n\n{desc}.\n")
        if not os.path.exists(p):
            parts.append("_missing on this machine_\n")
            continue
        try:
            df = pd.read_parquet(p) if p.endswith(".parquet") else pd.read_csv(p)
        except Exception as e:  # pragma: no cover
            parts.append(f"_could not read: {e}_\n")
            continue
        wide = df.shape[1] > 30
        parts.append(f"Rows: {len(df):,}. Columns: {df.shape[1]}." + (" Wide panel: index = date, one column per ticker." if wide else "") + "\n")
        if wide:
            parts.append(f"\nIndex range: {df.index.min()} to {df.index.max()}; example columns: {', '.join(map(str, list(df.columns)[:12]))} ...\n")
            continue
        ex = df.iloc[len(df) // 2] if len(df) else None
        rows = [{"column": c, "dtype": str(df[c].dtype), "non_null": int(df[c].notna().sum()),
                 "example": "" if ex is None else str(ex[c])[:80]} for c in df.columns]
        parts.append(md_table(pd.DataFrame(rows)))
    write("data_dictionary.md", "\n".join(parts))


